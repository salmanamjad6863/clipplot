-- ClipPilot schema v3 — workspaces (one per YouTube channel)
-- Run once in Supabase → SQL Editor → New query → paste → Run. Safe to re-run.
-- Everything that exists today moves into the "Main" workspace.

create table if not exists workspaces (
  id          uuid primary key default gen_random_uuid(),
  name        text not null,
  created_at  timestamptz not null default now()
);
alter table workspaces enable row level security;

insert into workspaces (id, name) values ('00000000-0000-4000-8000-000000000001', 'Main')
on conflict (id) do nothing;

-- ---------- settings: one row per workspace ----------
alter table settings add column if not exists workspace_id uuid references workspaces(id) on delete cascade;
update settings set workspace_id = '00000000-0000-4000-8000-000000000001' where workspace_id is null;
alter table settings alter column workspace_id set not null;
create unique index if not exists settings_workspace_uidx on settings (workspace_id);
-- id was pinned to 1 (single row) → make it an ordinary auto id
alter table settings drop constraint if exists settings_id_check;
alter table settings alter column id drop default;
do $$ begin
  alter table settings alter column id add generated by default as identity (start with 100);
exception when others then null; end $$;

-- ---------- games: per workspace (own fallback order + playlists) ----------
alter table trends drop constraint if exists trends_game_slug_fkey;
alter table clips  drop constraint if exists clips_game_slug_fkey;
alter table games add column if not exists workspace_id uuid references workspaces(id) on delete cascade;
update games set workspace_id = '00000000-0000-4000-8000-000000000001' where workspace_id is null;
alter table games alter column workspace_id set not null;
do $$ begin
  alter table games drop constraint games_pkey;
  alter table games add primary key (workspace_id, slug);
exception when others then null; end $$;

-- ---------- trends: never-repeat is per workspace ----------
alter table trends add column if not exists workspace_id uuid references workspaces(id) on delete cascade;
update trends set workspace_id = '00000000-0000-4000-8000-000000000001' where workspace_id is null;
alter table trends alter column workspace_id set not null;
alter table trends drop constraint if exists trends_youtube_video_id_key;
create unique index if not exists trends_ws_video_uidx on trends (workspace_id, youtube_video_id);
create index if not exists trends_ws_found_idx on trends (workspace_id, found_at desc);

-- ---------- clips ----------
alter table clips add column if not exists workspace_id uuid references workspaces(id) on delete cascade;
update clips set workspace_id = '00000000-0000-4000-8000-000000000001' where workspace_id is null;
alter table clips alter column workspace_id set not null;
create index if not exists clips_ws_created_idx on clips (workspace_id, created_at desc);

